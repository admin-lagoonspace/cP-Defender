#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════
# apachectl — A STUB. NOT APACHE. NOT MODSECURITY.
#
# ── WHY THIS EXISTS AT ALL ────────────────────────────────────────────────────
#
# With no apachectl on PATH, WAFInstaller::validateApache() returns ok=false,
# so EVERY call to setMode() takes the rollback branch. The whole of 7f397eb --
# snapshot, write, validate, restore -- was unreachable in this container: the
# code could not be exercised on Linux at all, which is the one thing the
# container is for.
#
# ── WHAT IT DOES AND DOES NOT CHECK ──────────────────────────────────────────
#
# It does ONE real thing: `-t` walks the config that our include points at,
# follows IncludeOptional globs, and fails on a DUPLICATE SecRule id. That is
# the actual fault that took host.lws-s1.com down on 7 Nov:
#
#   AH00526: Syntax error on line 56 of .../REQUEST-913-SCANNER-DETECTION.conf
#   ModSecurity: Found another rule with the same id
#
# So a duplicate id generated by WAFExclusions IS caught here, for real.
#
# It does NOT:
#   - parse Apache's configuration grammar
#   - load or evaluate ModSecurity
#   - validate SecRule operators, actions, phases, or chaining
#   - know whether ctl:ruleRemoveById is legal where it was written
#
# A PASS FROM THIS STUB IS NOT EVIDENCE THAT APACHE ACCEPTS THE CONFIG.
# Anything resting on real directive syntax has to be proven on a box with
# httpd and mod_security2 installed, and Shakaal's report says so rather than
# counting this as coverage.
#
# Override the verdict for failure-path tests:
#   echo reject > /etc/serverscrub-apachectl-verdict
#   rm -f       /etc/serverscrub-apachectl-verdict      # back to real checking
# ═══════════════════════════════════════════════════════════════════════════════
set -uo pipefail

VERDICT_FILE=/etc/serverscrub-apachectl-verdict

if [[ "${1:-}" != "-t" ]]; then
    # graceful / restart / anything else: there is no httpd to signal.
    echo "apachectl stub: '${1:-}' is a no-op in the test container"
    exit 0
fi

if [[ -f "$VERDICT_FILE" ]] && grep -qi reject "$VERDICT_FILE"; then
    echo "AH00526: Syntax error on line 56 of /etc/serverscrub/waf/coreruleset/rules/REQUEST-913-SCANNER-DETECTION.conf:"
    echo "ModSecurity: Found another rule with the same id"
    exit 1
fi

# Collect every file Apache would read through our include, one level of
# IncludeOptional deep (which is as deep as our own config goes).
shopt -s nullglob
declare -a FILES=()
for inc in /etc/apache2/conf.d/zz-serverscrub-waf.conf \
           /etc/httpd/conf.d/zz-serverscrub-waf.conf; do
    [[ -f "$inc" ]] || continue
    FILES+=("$inc")
    while read -r _d target; do
        [[ -n "${target:-}" ]] || continue
        for g in $target; do [[ -f "$g" ]] && FILES+=("$g"); done
    done < <(grep -hE '^[[:space:]]*IncludeOptional' "$inc" 2>/dev/null)
done

# Second level: our own conf includes the CRS rule glob.
for f in "${FILES[@]}"; do
    while read -r _d target; do
        [[ -n "${target:-}" ]] || continue
        for g in $target; do [[ -f "$g" ]] && FILES+=("$g"); done
    done < <(grep -hE '^[[:space:]]*IncludeOptional' "$f" 2>/dev/null)
done

if [[ ${#FILES[@]} -eq 0 ]]; then
    echo "Syntax OK"
    exit 0
fi

# DEDUPE, or this reports a duplicate id for every rule. The two passes above
# both add serverscrub-waf.conf, so each `id:` in it was counted twice and
# `uniq -d` called the first one a collision -- a false rejection that made
# `waf exclude add` roll back a perfectly good config.
mapfile -t FILES < <(printf '%s\n' "${FILES[@]}" | awk '!seen[$0]++')

dupe=$(grep -hoE '\bid:[0-9]+' "${FILES[@]}" 2>/dev/null \
       | sort | uniq -d | head -1)
if [[ -n "$dupe" ]]; then
    where=$(grep -lE "\b${dupe}\b" "${FILES[@]}" 2>/dev/null | head -1)
    echo "AH00526: Syntax error on line 1 of ${where}:"
    echo "ModSecurity: Found another rule with the same id (${dupe})"
    exit 1
fi

echo "Syntax OK"
exit 0
